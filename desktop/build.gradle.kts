plugins {
    application
}

evaluationDependsOn(":core")

@Suppress("UNCHECKED_CAST")
val coreSources = project(":core").extra["coreSources"] as List<String>
@Suppress("UNCHECKED_CAST")
val coreExcludes = project(":core").extra["coreExcludes"] as List<String>

java {
    sourceCompatibility = JavaVersion.VERSION_1_8
    targetCompatibility = JavaVersion.VERSION_1_8
}

tasks.withType<JavaCompile>().configureEach {
    options.encoding = "UTF-8"
    options.release.set(8)
    options.compilerArgs.add("-Xlint:-options")
}

sourceSets {
    main {
        java {
            // Everything in src/ that is not part of :core (the Swing UI, model/controller, services).
            setSrcDirs(listOf("../src"))
            include("shuffle/fwk/**")
            // Only test files: a pattern spec also matches the parent directories of core files.
            val coreSpec = PatternSet().include(coreSources).exclude(coreExcludes).asSpec
            exclude { !it.isDirectory && coreSpec.isSatisfiedBy(it) }
            // Generated by the Ant build; :core generates its own copy.
            exclude("shuffle/fwk/ShuffleVersion.java")
        }
        resources {
            setSrcDirs(emptyList<String>())
        }
    }
    test {
        java {
            // Upstream tests live in src/shuffle/test; new desktop-only tests (parity) in desktop/src/test.
            setSrcDirs(listOf("../src", "src/test/java"))
            include("shuffle/test/**", "shuffle/parity/**")
        }
    }
}

dependencies {
    implementation(project(":core"))
    implementation("org.apache.ant:ant:1.9.6")
    testImplementation("junit:junit:4.13.2")
}

application {
    mainClass.set("shuffle.fwk.ShuffleController")
}

tasks.test {
    // The managers write user config relative to the working directory; keep it out of the repo.
    val work = layout.buildDirectory.dir("test-work").get().asFile
    workingDir = work
    doFirst { work.mkdirs() }
}

tasks.named<JavaExec>("run") {
    workingDir = rootProject.projectDir
}
